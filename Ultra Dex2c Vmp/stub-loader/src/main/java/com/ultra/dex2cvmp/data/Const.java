package com.ultra.dex2cvmp.data;

/**
 * Runtime constants for the DEX loader stub.
 *
 * All string literals are XOR-obfuscated so they never appear in the
 * DEX string pool as plaintext.  d(int[], int...) decrypts at call-site.
 */
public class Const {

    /** rotating-XOR decrypt: e[i] ^ k[i % k.length] */
    private static String d(int[] e, int... k) {
        char[] c = new char[e.length];
        for (int i = 0; i < e.length; i++) c[i] = (char)(e[i] ^ k[i % k.length]);
        return new String(c);
    }

    /** "phantom" */
    public static String getLib() {
        return d(new int[]{0x4A,0x19,0x5B,0x1F,0x4E,0x1E,0x57}, 0x3A,0x71);
    }

    /** "phantom.vmp" */
    public static String getBundleFile() {
        return d(new int[]{0x2C,0x45,0x70,0x32,0x59,0x7E,0x31,0x03,0x67,0x31,0x5D}, 0x5C,0x2D,0x11);
    }

    /** "app.cfg" */
    public static String getAppCfg() {
        return d(new int[]{0x25,0x6F,0x34,0x31,0x27,0x79,0x23}, 0x44,0x1F);
    }

    /** "ph_salt" */
    public static String getSaltAsset() {
        return d(new int[]{0x5B,0x06,0x74,0x1D,0x4A,0x02,0x5F}, 0x2B,0x6E);
    }

    /** "libphantom_arm64.blob" */
    public static String getBlobArm64() {
        return d(new int[]{0x16,0x7A,0x27,0x0A,0x7B,0x24,0x14,0x67,0x2A,0x17,0x4C,0x24,0x08,0x7E,0x73,0x4E,0x3D,0x27,0x16,0x7C,0x27}, 0x7A,0x13,0x45);
    }

    /** "libphantom_arm.blob" */
    public static String getBlobArm() {
        return d(new int[]{0x0D,0x40,0x31,0x11,0x41,0x32,0x0F,0x5D,0x3C,0x0C,0x76,0x32,0x13,0x44,0x7D,0x03,0x45,0x3C,0x03}, 0x61,0x29,0x53);
    }

    /**
     * Real Application class name — default is "android.app.Application".
     * DexProtector.install() overwrites this from assets/phantom/app.cfg.
     */
    private static String REAL_APP = null;

    public static String getRealApp() {
        if (REAL_APP == null)
            REAL_APP = d(new int[]{0x2C,0x57,0x18,0x3F,0x56,0x15,0x29,0x17,0x1D,0x3D,0x49,0x52,0x0C,0x49,0x0C,0x21,0x50,0x1F,0x2C,0x4D,0x15,0x22,0x57}, 0x4D,0x39,0x7C);
        return REAL_APP;
    }

    public static void setRealApp(String name) {
        if (name != null && !name.isEmpty()) REAL_APP = name;
    }
}
